import { getFidelizeConfig, fidelizeRequest, resolveFidelizePath } from "../../src/lib/fidelize.server";
const cfg = (await getFidelizeConfig())!;
const origin = new URL(cfg.baseUrl).origin;
const email = `homolog.sso.${Date.now()}@example.com`;
const prov: any = await fidelizeRequest(resolveFidelizePath(cfg.baseUrl, "/provision-account"), { config: cfg, method: "POST", body: { name: "Homolog SSO", email, phone: "11988887777", plan: "starter", source: "ronnei" } });
const token = (prov.data as any)?.autologin_token;
const url = `${origin}/auth/autologin?token=${encodeURIComponent(token)}`;
console.log("provision HTTP", prov.httpCode, "token?", Boolean(token));
console.log("autologin URL:", url);
const r = await fetch(url, { redirect: "manual", headers: { "user-agent": "Mozilla/5.0" } });
console.log("autologin HTTP", r.status, "location:", r.headers.get("location"));
const body = await r.text();
console.log("body head:", body.slice(0, 300).replace(/\s+/g, " "));
